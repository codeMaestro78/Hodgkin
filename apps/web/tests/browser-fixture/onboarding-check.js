async (page) => {
  const base = "http://127.0.0.1:3101";
  const checks = [];
  const assert = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };
  await page.goto(base + "/?view=onboarding");
  // Earlier checks share this tab; start from no onboarding state and no recovered composer draft.
  await page.evaluate(() => sessionStorage.clear());
  await page.reload();
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole("heading", { name: "What best describes you?" }).waitFor();
  assert(await page.getByRole("button", { name: "Continue", exact: true }).isDisabled(), "Setup requires a role before continuing");
  await page.getByRole("button", { name: /Engineer \/ builder/ }).click();
  assert(await page.getByLabel("Your role", { exact: true }).inputValue() === "Engineer / builder", "Role choices fill an editable custom field");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("heading", { name: "What’s your field?" }).waitFor();
  assert(await page.evaluate(() => document.activeElement.id === "onboarding-heading"), "Step changes focus the new heading for keyboard users");
  await page.getByLabel("Your field", { exact: true }).fill("Distributed systems");
  await page.evaluate(() => { window.fixtureOnboardingFail = true; });
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("alert").waitFor();
  assert(await page.getByLabel("Your field", { exact: true }).inputValue() === "Distributed systems", "Failed saves preserve typed answers and the current step");
  await page.evaluate(() => { window.fixtureOnboardingFail = false; });
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("heading", { name: "Where do you do your work?" }).waitFor();
  await page.getByRole("button", { name: /^Company/ }).click();
  await page.getByLabel("Organisation name").fill("Example research team");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("heading", { name: "What are you researching?" }).waitFor();
  await page.reload();
  await page.getByRole("heading", { name: "What are you researching?" }).waitFor();
  assert(true, "Reload resumes the last saved step");
  await page.getByRole("button", { name: "Back", exact: true }).click();
  await page.getByRole("heading", { name: "Where do you do your work?" }).waitFor();
  assert(await page.getByLabel("Organisation name").inputValue() === "Example research team", "Back navigation retains workplace details");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("heading", { name: "What are you researching?" }).waitFor();
  const question = "How do durable research agents recover after a worker crash?";
  await page.getByLabel("Your first research question").fill(question);
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("heading", { name: "How much ground should we cover?" }).waitFor();
  await page.getByRole("button", { name: /^Focused/ }).click();
  assert(await page.getByText("No payment or subscription is selected here.").isVisible(), "Depth selection does not fabricate subscription billing");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("heading", { name: "Your workspace, ready for you." }).waitFor();
  assert(await page.locator(".onboarding-review").innerText().then((text) => text.includes(question) && text.includes("Focused")), "Review shows the actual question and depth choices");
  await page.getByRole("button", { name: "Edit Role", exact: true }).click();
  await page.getByRole("heading", { name: "What best describes you?" }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile onboarding has no horizontal overflow");
  await page.emulateMedia({ reducedMotion: "reduce" });
  assert(await page.locator(".onboarding-step").evaluate((element) => getComputedStyle(element).animationName === "none"), "Reduced motion disables step animation");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.getByLabel("Your role", { exact: true }).fill("Technical researcher");
  for (let i = 0; i < 5; i++) {
    await page.getByRole("button", { name: "Continue", exact: true }).click();
    await page.getByRole("status").filter({ hasText: "Progress saved" }).waitFor();
  }
  await page.getByRole("button", { name: "Open my workspace", exact: true }).click();
  await page.getByRole("heading", { name: "Start a research brief." }).waitFor();
  await page.waitForFunction(() => document.querySelector("#question").value.length > 0);
  assert(await page.getByLabel("What do you need to understand?").inputValue() === question, "Completion prepares the question in the composer");
  assert(await page.getByRole("button", { name: /^Focused/ }).getAttribute("aria-pressed") === "true", "Completion applies the selected depth within existing limits");
  assert(await page.evaluate(() => !window.fixtureSubmission), "Onboarding never automatically dispatches research");
  await page.goto(base + "/?view=onboarding");
  await page.getByRole("heading", { name: "What best describes you?" }).waitFor();
  await page.getByRole("button", { name: "Skip setup", exact: true }).click();
  await page.getByRole("heading", { name: "Start a research brief." }).waitFor();
  assert(await page.evaluate(() => JSON.parse(sessionStorage.getItem("fixture-onboarding")).status === "skipped"), "Skipping persists so the flow is not repeatedly forced");
  return { checksPassed: checks.length, checks };
}
