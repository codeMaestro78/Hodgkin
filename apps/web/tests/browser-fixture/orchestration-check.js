async (page) => {
  const base = "http://127.0.0.1:3101";
  const checks = [];
  const assert = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };
  await page.setViewportSize({ width: 1440, height: 900 });
  // A live run: only an unfinished run can have a running task.
  await page.goto(base + "/?view=run&state=verifying&tasks=staged");
  const panel = page.locator(".report-orchestration");
  await panel.waitFor();
  assert((await panel.locator("summary").innerText()).includes("1 failed"), "Orchestration summary counts failed tasks");
  await page.getByText(/Inspect live orchestration/).click();
  const stages = panel.locator(".execution-stage");
  assert(await stages.count() === 3, "Graph renders three stage lanes");
  assert(await stages.nth(0).getByText("Planner delta").isVisible(), "Coverage-repair planning is grouped with the plan stage");
  assert(await stages.nth(1).getAttribute("data-state") === "failed", "A failed collector marks its stage as failed");
  assert(await stages.nth(2).getAttribute("data-state") === "active", "Assessment stage is populated and active");
  assert(await stages.nth(2).getByText("Verifier").isVisible() && await stages.nth(2).getByText("Reflector").isVisible(), "Assessment tasks render in the third stage");
  assert(await stages.nth(2).getByText(/attempt 2/).isVisible(), "Retried tasks show their attempt number");
  const loop = panel.locator(".orch-loop");
  assert(await loop.isVisible() && await loop.getAttribute("data-taken") === "true", "Loop-back is highlighted after a coverage repair");
  assert((await loop.innerText()).includes("returned to the planner once"), "Loop-back states how often coverage repair ran");
  const failed = panel.locator('.execution-node[data-status="failed"]').filter({ hasText: "Search regulatory filings" });
  await failed.click();
  const detail = page.getByRole("region", { name: "Selected task details" });
  assert(await detail.locator(".orch-glyph[data-status=\"failed\"]").isVisible(), "Failed task detail shows the failure glyph");
  assert((await detail.locator(".orch-error").innerText()).includes("provider unavailable"), "Failed task detail explains its error");
  await detail.getByRole("button", { name: "Planner" }).click();
  assert((await detail.getByRole("heading").innerText()) === "Planner", "Dependency chips navigate to the upstream task");
  await page.goto(base + "/?view=run&tasks=staged");
  await page.getByRole("heading", { name: "Direct answer", exact: true }).waitFor();
  const ended = page.locator(".report-orchestration");
  await ended.locator("summary").click();
  assert(!(await ended.locator("summary").innerText()).includes("running") && await ended.locator('.execution-node[data-status="running"]').count() === 0, "An ended run shows no task as still running");
  await page.goto(base + "/?view=run&state=awaiting_approval");
  const clock = page.locator(".report-meta .run-clock");
  await clock.filter({ hasText: "paused for approval" }).waitFor();
  const paused = await clock.innerText();
  assert(paused.startsWith("0m 20s elapsed"), "Clock excludes the open approval wait");
  await page.waitForTimeout(2500);
  assert(await clock.innerText() === paused, "Clock stays stopped while the plan awaits a decision");
  await page.getByRole("button", { name: "Approve plan", exact: true }).click();
  await page.getByText("Plan approved. Research is queued.").waitFor();
  assert(await page.evaluate(() => window.fixtureDecision) === "approve", "Approval decision reaches the API");
  await page.waitForTimeout(2500);
  const resumed = await clock.innerText();
  const seconds = Number(/^0m (\d+)s elapsed/.exec(resumed)?.[1]);
  assert(!resumed.includes("paused") && seconds >= 21 && seconds <= 24, "Clock resumes after approval without counting the wait");
  return { checksPassed: checks.length, checks };
}
