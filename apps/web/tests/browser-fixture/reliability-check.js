async (page) => {
  const base = "http://127.0.0.1:3101";
  const checks = [];
  const assert = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base + "/?view=run");
  await page.getByRole("heading", { name: "Direct answer", exact: true }).waitFor();
  await page.getByText(/Inspect live orchestration/).click();
  await page.getByRole("button", { name: /Find original evidence/ }).first().click();
  assert(await page.getByRole("region", { name: "Selected task details" }).isVisible(), "Graph nodes open persisted task details");
  await page.getByRole("button", { name: "Task list", exact: true }).first().click();
  assert(await page.locator(".report-orchestration .execution-list").isVisible(), "Orchestration has an accessible task-list alternative");
  await page.getByRole("button", { name: "Investigate gap", exact: true }).click();
  await page.getByText("Fixture investigation creation failed").waitFor();
  const first = await page.evaluate(() => window.fixtureFollowup);
  assert(first.gapId === "gap-a", "Gap investigation uses a real follow-up request with its gap reference");
  await page.getByRole("button", { name: "Investigate gap", exact: true }).click();
  const second = await page.evaluate(() => window.fixtureFollowup);
  assert(first.idempotencyKey === second.idempotencyKey, "Failed follow-up submissions retain their idempotency key");
  await page.getByRole("tab", { name: /^Checks/ }).click();
  await page.getByLabel("Verification status").selectOption("insufficient_evidence");
  assert(await page.getByRole("heading", { name: "A draft assertion has insufficient evidence." }).isVisible(), "Checks filter displays insufficient-evidence assertions");
  assert(!await page.getByRole("heading", { name: "Each claim should remain connected to evidence." }).isVisible(), "Filtering hides supported assertions without changing their data");
  await page.getByLabel("Verification status").selectOption("contradicted");
  await page.getByText("No claims match").waitFor();
  assert(true, "Claim filters have an explicit empty state");
  await page.getByRole("tab", { name: /^Sources/ }).click();
  await page.getByRole("button", { name: /^Inspect Architecture/ }).click();
  await page.getByText("Source assessment and limitations").click();
  assert(await page.getByText("Publisher authority has not been independently assessed.").isVisible(), "Evidence inspector explains missing source authority");
  await page.getByText("Retrieved surrounding context").click();
  assert(await page.getByText("Retrieved context. Evidence must remain inspectable. Additional source context.").isVisible(), "Evidence inspector separates retrieved context from matched quotes");
  await page.getByLabel("Report version").selectOption("2");
  await page.getByRole("heading", { name: "Revised findings", exact: true }).waitFor();
  assert(true, "Selecting a report version fetches its preserved Markdown");
  await page.emulateMedia({ media: "print" });
  assert(await page.locator(".print-report").isVisible(), "PDF printing uses the versioned evidence export");
  assert(!await page.locator(".report-article").isVisible(), "Printing does not duplicate the on-screen report");
  await page.emulateMedia({ media: "screen" });
  await page.goto(base + "/?view=run&state=writing");
  await page.getByRole("tab", { name: /^Methodology/ }).click();
  await page.getByRole("button", { name: /Find original evidence/ }).click();
  await page.evaluate(() => { window.fixtureRun.insights.tasks[1].status = "completed"; window.fixtureRun.insights.tasks[1].completedAt = new Date().toISOString(); window.fixtureStream.onmessage(new MessageEvent("message", { data: JSON.stringify({ sequence: 2 }) })); });
  await page.locator('.evidence-panel .execution-node[data-status="completed"]').filter({ hasText: "Find original evidence" }).waitFor();
  assert(true, "SSE refresh updates actual snapshot task states without a progress timer");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base + "/?view=run");
  await page.getByRole("button", { name: "Evidence", exact: true }).click();
  await page.getByRole("tab", { name: /^Methodology/ }).click();
  assert(await page.locator(".evidence-panel .execution-list").isVisible(), "Mobile orchestration defaults to a task list");
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile task details do not overflow the viewport");
  return { checksPassed: checks.length, checks };
}
