async (page) => {
  const base = "http://127.0.0.1:3101";
  const checks = [];
  const assert = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base + "/?view=run");
  await page.getByRole("heading", { name: "Direct answer", exact: true }).waitFor();
  const trigger = page.getByRole("button", { name: "Share and export report" });
  const panel = page.getByRole("dialog", { name: "Share and export" });
  assert(!await panel.isVisible(), "Share panel starts closed");
  await trigger.click();
  await panel.waitFor();
  await panel.evaluate((element) => Promise.all(element.getAnimations().map((animation) => animation.finished)));
  assert(await panel.getByText("No active links. New links expire after 7 days.").isVisible(), "Share panel explains the empty link state");
  const box = await panel.boundingBox();
  const anchor = await trigger.boundingBox();
  assert(box.y >= anchor.y + anchor.height && box.x + box.width <= 1440, "Share panel opens below its trigger inside the viewport");
  await panel.getByRole("button", { name: "Create link", exact: true }).click();
  const link = panel.getByLabel("Copyable, expiring share link");
  await link.waitFor();
  assert((await link.inputValue()).endsWith("/shared/fixture-token-share-1"), "Created link stays visible and copyable");
  await panel.locator('[role="status"]', { hasText: /expires in 7 days/ }).waitFor();
  assert(true, "Creation explains the link expiry");
  const active = panel.getByRole("list", { name: "Active share links" }).getByRole("listitem");
  await active.first().waitFor();
  assert(await active.count() === 1 && /Expires in 7 days/.test(await active.first().innerText()), "Active links list their expiry");
  assert(await trigger.innerText().then((text) => text.includes("1")), "Trigger counts active links");
  await panel.getByRole("button", { name: /Revoke share link expiring/ }).click();
  await panel.getByText("Share link revoked. New visits are blocked.").waitFor();
  assert(await panel.getByText("1 revoked or expired link no longer opens.").isVisible(), "Revoked links leave the active list");
  await panel.getByRole("button", { name: "Export Markdown" }).click();
  await panel.getByText("Markdown export downloaded.").waitFor();
  assert(await page.evaluate(() => window.fixtureDownloads) === 1, "Markdown export downloads the saved artifact");
  const receipt = await panel.locator(".share-pop__receipt").innerText();
  assert(receipt.includes("Version 2") && receipt.includes("4.1 KB") && receipt.includes("SHA-256 3f9a51c2") && receipt.includes("Checksum verified"), "Export receipt shows version, size and checksum");
  await panel.getByRole("button", { name: "Export BibTeX" }).click();
  const status = panel.getByRole("status");
  await panel.getByText("Fixture BibTeX export failed. Retry the export.").waitFor();
  assert(await status.getAttribute("data-tone") === "error", "Export failures are styled as errors");
  await page.keyboard.press("Escape");
  await panel.waitFor({ state: "hidden" });
  assert(await page.evaluate(() => document.activeElement?.getAttribute("aria-label")) === "Share and export report", "Escape closes the panel and returns focus to the trigger");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base + "/?view=run");
  await page.getByRole("heading", { name: "Direct answer", exact: true }).waitFor();
  await page.getByRole("button", { name: "Share and export report" }).click();
  await panel.waitFor();
  await panel.evaluate((element) => Promise.all(element.getAnimations().map((animation) => animation.finished)));
  const sheet = await panel.boundingBox();
  assert(sheet.x >= 8 && sheet.x + sheet.width <= 382 && sheet.y + sheet.height <= 836, "Mobile share panel is a bottom sheet inside the viewport");
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile share panel does not overflow the page");
  return { checksPassed: checks.length, checks };
}
